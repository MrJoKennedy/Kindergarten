-- Физическая модель БД «Дошкольный центр развития ребёнка»
-- СУБД: PostgreSQL 18 (скрипт совместим с PostgreSQL 15 и новее)
-- Кодировка базы данных: UTF8

-- CREATE DATABASE kindergarten_center ENCODING 'UTF8' TEMPLATE template0;

CREATE SCHEMA IF NOT EXISTS center;
SET search_path TO center;

-- ===== Домены =====
CREATE DOMAIN d_phone AS varchar(20)
    CONSTRAINT ck_d_phone CHECK (VALUE ~ '^[0-9+() -]{5,20}$');  -- телефон: цифры, «+», «-», пробел, скобки; 5–20 символов
CREATE DOMAIN d_age AS numeric(2,1)
    CONSTRAINT ck_d_age CHECK (VALUE BETWEEN 1.5 AND 7.0);  -- возраст в годах: от 1,5 до 7,0
CREATE DOMAIN d_gender AS char(1)
    CONSTRAINT ck_d_gender CHECK (VALUE IN ('М','Ж'));  -- пол: М или Ж
CREATE DOMAIN d_weekday AS smallint
    CONSTRAINT ck_d_weekday CHECK (VALUE BETWEEN 1 AND 7);  -- день недели: 1 (понедельник) … 7 (воскресенье)
CREATE DOMAIN d_relation AS varchar(20)
    CONSTRAINT ck_d_relation CHECK (VALUE IN ('мать','отец','бабушка','дедушка','опекун','другое'));  -- степень родства
CREATE DOMAIN d_count AS integer
    CONSTRAINT ck_d_count CHECK (VALUE > 0);  -- положительное целое число
CREATE DOMAIN d_years AS integer
    CONSTRAINT ck_d_years CHECK (VALUE >= 0);  -- неотрицательное целое число (стаж, лет)
CREATE DOMAIN d_money AS numeric(10,2)
    CONSTRAINT ck_d_money CHECK (VALUE >= 0);  -- денежная сумма, не меньше 0

-- ===== Таблицы =====

-- Направление развития
CREATE TABLE direction (
    direction_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    name varchar(100) NOT NULL,
    CONSTRAINT pk_direction PRIMARY KEY (direction_no),
    CONSTRAINT uq_direction_name UNIQUE (name)
);

-- Программа занятий
CREATE TABLE program (
    program_code varchar(20) NOT NULL,
    name varchar(100) NOT NULL,
    description varchar(1000),
    min_age d_age NOT NULL,
    max_age d_age NOT NULL,
    lesson_minutes d_count NOT NULL,
    lessons_count d_count NOT NULL,
    price d_money NOT NULL,
    max_children d_count NOT NULL,
    CONSTRAINT pk_program PRIMARY KEY (program_code),
    CONSTRAINT ck_program_age CHECK (max_age >= min_age)
);

-- Принадлежность программы направлению
CREATE TABLE program_direction (
    program_code varchar(20) NOT NULL,
    direction_no integer NOT NULL,
    CONSTRAINT pk_program_direction PRIMARY KEY (program_code, direction_no),
    CONSTRAINT fk_program_direction_program FOREIGN KEY (program_code) REFERENCES program (program_code) ON DELETE CASCADE,
    CONSTRAINT fk_program_direction_direction FOREIGN KEY (direction_no) REFERENCES direction (direction_no) ON DELETE RESTRICT
);

-- Сотрудник
CREATE TABLE employee (
    employee_no integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    last_name varchar(50) NOT NULL,
    first_name varchar(50) NOT NULL,
    patronymic varchar(50) NOT NULL,
    phone d_phone NOT NULL,
    manager_no integer,
    CONSTRAINT pk_employee PRIMARY KEY (employee_no),
    CONSTRAINT fk_employee_manager FOREIGN KEY (manager_no) REFERENCES employee (employee_no) ON DELETE SET NULL,
    CONSTRAINT ck_employee_manager CHECK (manager_no <> employee_no)
);

-- Педагог
CREATE TABLE teacher (
    employee_no integer NOT NULL,
    education varchar(100) NOT NULL,
    experience_years d_years NOT NULL,
    CONSTRAINT pk_teacher PRIMARY KEY (employee_no),
    CONSTRAINT fk_teacher_employee FOREIGN KEY (employee_no) REFERENCES employee (employee_no) ON DELETE CASCADE
);

-- Администратор
CREATE TABLE administrator (
    employee_no integer NOT NULL,
    job_title varchar(100) NOT NULL,
    CONSTRAINT pk_administrator PRIMARY KEY (employee_no),
    CONSTRAINT fk_administrator_employee FOREIGN KEY (employee_no) REFERENCES employee (employee_no) ON DELETE CASCADE
);

-- Специализация педагога
CREATE TABLE teacher_direction (
    employee_no integer NOT NULL,
    direction_no integer NOT NULL,
    CONSTRAINT pk_teacher_direction PRIMARY KEY (employee_no, direction_no),
    CONSTRAINT fk_teacher_direction_teacher FOREIGN KEY (employee_no) REFERENCES teacher (employee_no) ON DELETE CASCADE,
    CONSTRAINT fk_teacher_direction_direction FOREIGN KEY (direction_no) REFERENCES direction (direction_no) ON DELETE RESTRICT
);

-- Группа
CREATE TABLE study_group (
    group_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    program_code varchar(20) NOT NULL,
    teacher_no integer NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    seats d_count NOT NULL,
    CONSTRAINT pk_study_group PRIMARY KEY (group_no),
    CONSTRAINT fk_study_group_program FOREIGN KEY (program_code) REFERENCES program (program_code) ON DELETE RESTRICT,
    CONSTRAINT fk_study_group_teacher FOREIGN KEY (teacher_no) REFERENCES teacher (employee_no) ON DELETE RESTRICT,
    CONSTRAINT ck_study_group_dates CHECK (end_date >= start_date)
);

-- Расписание
CREATE TABLE schedule (
    group_no integer NOT NULL,
    weekday d_weekday NOT NULL,
    start_time time(0) NOT NULL,
    room_no varchar(10) NOT NULL,
    CONSTRAINT pk_schedule PRIMARY KEY (group_no, weekday, start_time),
    CONSTRAINT fk_schedule_group FOREIGN KEY (group_no) REFERENCES study_group (group_no) ON DELETE CASCADE,
    CONSTRAINT uq_schedule_room UNIQUE (room_no, weekday, start_time)
);

-- Проведённое занятие
CREATE TABLE lesson (
    lesson_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    group_no integer NOT NULL,
    lesson_date date NOT NULL,
    start_time time(0) NOT NULL,
    CONSTRAINT pk_lesson PRIMARY KEY (lesson_no),
    CONSTRAINT fk_lesson_group FOREIGN KEY (group_no) REFERENCES study_group (group_no) ON DELETE RESTRICT,
    CONSTRAINT uq_lesson_group_date UNIQUE (group_no, lesson_date, start_time)
);

-- Ребёнок
CREATE TABLE child (
    card_no integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    last_name varchar(50) NOT NULL,
    first_name varchar(50) NOT NULL,
    patronymic varchar(50) NOT NULL,
    birth_date date NOT NULL,
    gender d_gender NOT NULL,
    admission_date date NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_child PRIMARY KEY (card_no),
    CONSTRAINT ck_child_age CHECK (admission_date >= birth_date + INTERVAL '18 months' AND admission_date < birth_date + INTERVAL '85 months')
);

-- Сведения о здоровье
CREATE TABLE health_record (
    record_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    card_no integer NOT NULL,
    health_state varchar(1000),
    allergies varchar(1000),
    CONSTRAINT pk_health_record PRIMARY KEY (record_no),
    CONSTRAINT fk_health_record_child FOREIGN KEY (card_no) REFERENCES child (card_no) ON DELETE CASCADE,
    CONSTRAINT uq_health_record_child UNIQUE (card_no)
);

-- Родитель
CREATE TABLE parent (
    parent_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    last_name varchar(50) NOT NULL,
    first_name varchar(50) NOT NULL,
    patronymic varchar(50) NOT NULL,
    address varchar(200) NOT NULL,
    mobile_phone d_phone,
    work_phone d_phone,
    CONSTRAINT pk_parent PRIMARY KEY (parent_no),
    CONSTRAINT ck_parent_phone CHECK (mobile_phone IS NOT NULL OR work_phone IS NOT NULL)
);

-- Представительство (ребёнок — родитель)
CREATE TABLE child_parent (
    card_no integer NOT NULL,
    parent_no integer NOT NULL,
    relation d_relation NOT NULL,
    CONSTRAINT pk_child_parent PRIMARY KEY (card_no, parent_no),
    CONSTRAINT fk_child_parent_child FOREIGN KEY (card_no) REFERENCES child (card_no) ON DELETE CASCADE,
    CONSTRAINT fk_child_parent_parent FOREIGN KEY (parent_no) REFERENCES parent (parent_no) ON DELETE RESTRICT
);

-- Зачисление
CREATE TABLE enrollment (
    enrollment_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    card_no integer NOT NULL,
    group_no integer NOT NULL,
    enroll_date date NOT NULL DEFAULT CURRENT_DATE,
    leave_date date,
    CONSTRAINT pk_enrollment PRIMARY KEY (enrollment_no),
    CONSTRAINT fk_enrollment_child FOREIGN KEY (card_no) REFERENCES child (card_no) ON DELETE CASCADE,
    CONSTRAINT fk_enrollment_group FOREIGN KEY (group_no) REFERENCES study_group (group_no) ON DELETE RESTRICT,
    CONSTRAINT uq_enrollment UNIQUE (card_no, group_no, enroll_date),
    CONSTRAINT ck_enrollment_dates CHECK (leave_date IS NULL OR leave_date >= enroll_date)
);

-- Оплата
CREATE TABLE payment (
    payment_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    enrollment_no integer NOT NULL,
    amount numeric(10,2) NOT NULL,
    payment_date date NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_payment PRIMARY KEY (payment_no),
    CONSTRAINT fk_payment_enrollment FOREIGN KEY (enrollment_no) REFERENCES enrollment (enrollment_no) ON DELETE CASCADE,
    CONSTRAINT ck_payment_amount CHECK (amount > 0)
);

-- Посещаемость
CREATE TABLE attendance (
    attendance_no integer GENERATED ALWAYS AS IDENTITY NOT NULL,
    enrollment_no integer NOT NULL,
    lesson_no integer NOT NULL,
    is_present boolean NOT NULL DEFAULT true,
    absence_reason varchar(1000),
    CONSTRAINT pk_attendance PRIMARY KEY (attendance_no),
    CONSTRAINT fk_attendance_enrollment FOREIGN KEY (enrollment_no) REFERENCES enrollment (enrollment_no) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_lesson FOREIGN KEY (lesson_no) REFERENCES lesson (lesson_no) ON DELETE CASCADE,
    CONSTRAINT uq_attendance UNIQUE (enrollment_no, lesson_no),
    CONSTRAINT ck_attendance_reason CHECK (NOT is_present OR absence_reason IS NULL)
);

